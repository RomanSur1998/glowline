struct DotMatrixText: View {
    let text: String
    var dot: CGFloat = 3
    var spacing: CGFloat = 1
    var color: Color = Theme.text

    private var pitch: CGFloat { dot + spacing }
    private var width: CGFloat {
        CGFloat(max(text.count * (DotFont.columns + 1) - 1, 0)) * pitch
    }

    var body: some View {
        Canvas { context, _ in
            for (index, character) in text.enumerated() {
                let originX = CGFloat(index * (DotFont.columns + 1)) * pitch
                for (row, line) in DotFont.glyph(character).enumerated() {
                    for (column, cell) in line.enumerated() where cell == "#" {
                        let rect = CGRect(x: originX + CGFloat(column) * pitch, y: CGFloat(row) * pitch, width: dot, height: dot)
                        context.fill(Path(ellipseIn: rect), with: .color(color))
                    }
                }
            }
        }
        .frame(width: width, height: CGFloat(DotFont.rows) * pitch - spacing)
        .accessibilityLabel(text)
    }
}
